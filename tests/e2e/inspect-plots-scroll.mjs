import { chromium } from 'playwright';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1920, height: 1080 } });
const page = await ctx.newPage();
await page.goto('http://127.0.0.1:4173', { waitUntil: 'networkidle' });
await page.waitForTimeout(500);
const proj = page.locator('[data-action="open-project"]').first();
if (await proj.count()) await proj.click();
await page.waitForTimeout(400);
const navBtn = page.locator('text=剧情开发').first();
if (await navBtn.count()) await navBtn.click();
await page.waitForTimeout(800);
const m = await page.evaluate(() => {
  const nav = document.querySelector('header, .app-topbar, [data-app-topbar], nav');
  const navH = nav?.getBoundingClientRect().height;
  const navBottom = nav ? nav.getBoundingClientRect().bottom : 0;
  const actsRow = document.querySelector('.pgrid-hrow--acts .pgrid-hcell');
  const nodeRow = document.querySelector('.pgrid-hrow--nodes .pgrid-hcell');
  return { navH, navBottom, actsH: actsRow.getBoundingClientRect().height, nodeH: nodeRow.getBoundingClientRect().height };
});
console.log(JSON.stringify(m, null, 2));
await page.evaluate(() => window.scrollTo(0, 400));
await page.waitForTimeout(200);
await page.screenshot({ path: 'tests/e2e/realcheck-shots/_plots-scrolled400.png', clip: { x: 0, y: 0, width: 900, height: 500 } });
await browser.close();
